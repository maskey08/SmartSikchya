def main():
    os.makedirs("data", exist_ok=True)

    all_examples = (
        [(q, "easy")   for q in EASY] +
        [(q, "medium") for q in MEDIUM] +
        [(q, "hard")   for q in HARD]
    )

    random.seed(42)
    random.shuffle(all_examples)

    split     = int(len(all_examples) * 0.8)
    train     = all_examples[:split]
    val       = all_examples[split:]

    for filename, rows in [("data/train.csv", train), ("data/val.csv", val)]:
        with open(filename, "w", newline="", encoding="utf-8") as f:
            writer = csv.writer(f)
            writer.writerow(["question_text", "label"])
            writer.writerows(rows)
        print(f"Written {len(rows)} rows → {filename}")

    from collections import Counter
    counts = Counter(label for _, label in all_examples)
    print(f"\nTotal: {len(all_examples)} examples")
    print(f"Distribution: {dict(counts)}")
    print("\nNow run: python train.py")

if __name__ == "__main__":
    main()
